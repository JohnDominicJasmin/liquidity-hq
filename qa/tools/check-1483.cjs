// Independent check of 20261001c: shape, placeholders, keys, and prod == dev blocks. Reads from git, not from the PR's own script.
const { execSync } = require('child_process');
const REF = process.argv[2] || "origin/pr1483";
const sh = (c) => execSync(c, { encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 });
const sql = sh(`git show ${REF}:supabase/migrations/20261001c_labels_translations_ko_zh_ar_ru.sql`).replace(/\r\n/g, '\n');
const L = JSON.parse(sh(`git show ${REF}:lib/labelDefaults.en.json`));
const keysSrc = sh(`git show ${REF}:lib/labelKeys.ts`);
const [prodPart, devPart] = sql.split(/\n--\s*DEV\b/);
const rowRe = /\('([A-Z0-9_]+)','([a-zA-Z-]{2,5})','((?:[^']|'')*)'\)/g;
const parse = (s, stripComment) => [...(stripComment ? s.replace(/^--\s?/gm, '') : s).matchAll(rowRe)].map((m) => ({ k: m[1], l: m[2], v: m[3].replace(/''/g, "'") }));
const prod = parse(prodPart, false);
const dev = devPart ? parse(devPart, true) : [];
const keys = [...new Set(prod.map((r) => r.k))];
const byLocale = prod.reduce((a, r) => ((a[r.l] = (a[r.l] || 0) + 1), a), {});
console.log('prod rows', prod.length, 'dev rows', dev.length, 'keys', keys.length, 'per locale', JSON.stringify(byLocale));
console.log('prod block ends with do nothing:', /on conflict \(key, locale\) do nothing;/.test(prodPart), '| any do update:', /do update/.test(sql));
const dupe = prod.length - new Set(prod.map((r) => r.k + '/' + r.l)).size;
console.log('duplicate key/locale in prod block:', dupe);
const devSame = dev.length === prod.length && dev.every((d, i) => d.k === prod[i].k && d.l === prod[i].l && d.v === prod[i].v);
console.log('dev block identical to prod block:', devSame);
const notRegistered = keys.filter((k) => !keysSrc.includes(`'${k}'`));
const noDefault = keys.filter((k) => typeof L[k] !== 'string');
console.log('keys not in labelKeys.ts:', notRegistered.length, notRegistered.slice(0, 5).join(' '), '| keys with no English default:', noDefault.length, noDefault.slice(0, 5).join(' '));
const ph = (s) => (s.match(/\{[a-zA-Z0-9_]+\}/g) || []).sort().join(',');
const phBad = prod.filter((r) => typeof L[r.k] === 'string' && ph(r.v) !== ph(L[r.k]));
console.log('placeholder mismatches vs English default:', phBad.length);
for (const r of phBad.slice(0, 8)) console.log('  ', r.k, r.l, 'en=[' + ph(L[r.k]) + '] tr=[' + ph(r.v) + ']');
const empty = prod.filter((r) => !r.v.trim());
const sameAsEn = prod.filter((r) => r.v === L[r.k]);
console.log('empty values:', empty.length, '| identical to English (untranslated):', sameAsEn.length, sameAsEn.slice(0, 10).map((r) => r.k + '/' + r.l).join(' '));
const legalOps = keys.filter((k) => /^(REFUND_|TERMS_SECTION_WARRANTY_|OPS_)/.test(k));
console.log('legal/ops keys included (should be 0):', legalOps.length);
const bt = prod.filter((r) => r.k === 'FAQ_Q_FREE_VS_PRO_A');
console.log('FAQ_Q_FREE_VS_PRO_A rows:', bt.length, '| any mention backtest-like word:', bt.some((r) => /backtest|백테스트|回测|бэктест|الاختبار الخلفي/i.test(r.v)));
require('fs').writeFileSync(__dirname + '/1483-keys.json', JSON.stringify(keys));
