-- #1818 option D (Draw Structure): a 12th Pro tool needs a 12th usage column, because the metering
-- RPC does not take a generic column name - it is an `elsif p_column = '<name>_count'` chain ending in
-- `else raise exception 'increment_ai_usage: invalid column %'`. The shared `tool_pool_count` column
-- does NOT make this migration unnecessary, because the pool is only incremented AFTER a per-tool
-- column increment succeeds (see `if p_pool_limit is not null` below).
--
-- THAT `else raise` IS WHY THE APP SHIPS BEFORE THIS IS APPLIED, and it is a guarantee rather than a
-- hope. `incrementToolUsage` runs BEFORE the xAI call (every one of the 15 metered routes does this -
-- the increment is a reservation, see 20261023a), and `lib/aiUsage.ts` turns an RPC error into a
-- blocked result rather than falling through. On a database without this column, a Draw Structure
-- request is refused before any xAI spend. An unmetered paid call is unreachable by construction.
-- The user-visible message for that state is deliberately NOT "daily limit reached" - see the
-- `not_enabled` reason in lib/aiUsage.ts, added with this change.
--
-- THE REPLACEMENT IS THE LIVE FUNCTION PLUS TWO BRANCHES, AND THAT IS PROVED BY CONSTRUCTION RATHER
-- THAN BY READING IT. This body was generated by inserting two `elsif` branches into the existing
-- body - one in the increment chain, one in the ROLLBACK chain - and diffing: 6 lines added, 0
-- removed, 0 changed. The risk here is not the new column (additive, reversible); it is that
-- `create or replace` on this function re-meters all twelve Pro tools at once, on a database with no
-- backups. A missed rollback branch would silently stop refunding one tool.
--
--   normalised md5 of the body this was derived from : 0e3306669162fc601dd22bf0b4b1f5a4
--   normalised md5 of the body below                 : 1ac55e216e7d23363d23cd187eacfa33
--
-- "Normalised" = comments stripped, whitespace collapsed, then md5. THAT NORMALISATION IS REQUIRED,
-- NOT A CONVENIENCE: a prod function body cannot be diffed against its repo migration directly,
-- because the comments are gone before Postgres sees them - something in the apply path strips them,
-- so `pg_get_functiondef` returns a comment-free body and every function looks modified. Zero of 14
-- functions in prod carry a `--`, while the repo source for `lhq_grant_signup_trial` has 21 such
-- lines. The first md5 above was confirmed to match the LIVE prod `increment_ai_usage_impl` exactly
-- (7646 chars both sides), with a positive control: a one-character code change flips the hash,
-- removing a comment does not. See docs/INFRASTRUCTURE.md section 9j.
--
-- A COROLLARY OF THAT STRIPPING, CHECKED HERE: a comment stripper cannot tell `--` in code from `--`
-- inside a string literal, so a `--` in an error message would be truncated silently and the function
-- would still be created. The two new branches contain no string literals at all; checked
-- mechanically (0 matches for a `--` inside single quotes anywhere in the new body).
--
-- NOT APPLIED. This is DDL on the shared database; production needs the owner's word, and the dev
-- project serves dev, qa AND staging. Nothing in the app requires it to be applied in order to ship.
--
